// Generates the server progression migration from the v3 catalog and economy config so the
// database rewards exactly what the app's catalog says. Re-run after a catalog change:
//   node scripts/build-progression-migration.mjs
import fs from 'fs';

const catalog = JSON.parse(fs.readFileSync('src/content/game/thrivefold_real_game_catalog_v3.json', 'utf8'));
const economy = JSON.parse(fs.readFileSync('src/content/game/progression_economy.v1.json', 'utf8'));
const lit = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

const tasks = catalog.taskDefinitions
  .map((t) => `(${lit(t.id)}, ${Number(t.points?.taskPoints) || 0}, ${Number(t.points?.xp) || 0}, ${t.points?.dailyGoalEligible === false ? 'false' : 'true'})`)
  .join(',\n  ');
const levels = catalog.levelDefinitions
  .map((l) => `(${l.level}, ${l.minimumCumulativeXp}, ${lit(l.checkpointId)})`)
  .join(',\n  ');
const unlocks = economy.unlocks.map((u) => `(${lit(u.id)}, ${u.cost}, ${u.minLevel})`).join(',\n  ');
const lc = economy.diamonds.levelClear;

const sql = `-- Server-authoritative progression (generated by scripts/build-progression-migration.mjs).
-- Rewards come from catalog tables, never from client-supplied values. Every reward is an
-- idempotent ledger row; balances, levels and unlocks are computed from the ledger.

create table if not exists public.thrivefold_task_rewards (
  task_id text primary key,
  task_points integer not null check (task_points >= 0),
  xp integer not null check (xp >= 0),
  daily_goal_eligible boolean not null default true
);

create table if not exists public.thrivefold_levels (
  level integer primary key check (level between 1 and 1000),
  min_xp integer not null check (min_xp >= 0),
  checkpoint_id text
);

create table if not exists public.thrivefold_feature_unlocks (
  id text primary key,
  cost integer not null check (cost > 0),
  min_level integer not null check (min_level >= 1)
);

create table if not exists public.thrivefold_reward_ledger (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  key text not null,
  kind text not null check (kind in ('task_reward','daily_goal','level_clear','unlock_spend','legacy_import')),
  xp integer not null default 0,
  diamonds integer not null default 0,
  task_points integer not null default 0,
  game_date date not null,
  source_id text not null,
  policy_version text not null,
  created_at timestamptz not null default now(),
  unique (user_id, key)
);
create index if not exists thrivefold_reward_ledger_user_date on public.thrivefold_reward_ledger (user_id, game_date);

create table if not exists public.thrivefold_feature_entitlements (
  user_id uuid not null references auth.users(id) on delete cascade,
  feature_id text not null references public.thrivefold_feature_unlocks(id),
  granted_at timestamptz not null default now(),
  primary key (user_id, feature_id)
);

alter table public.thrivefold_task_rewards enable row level security;
alter table public.thrivefold_levels enable row level security;
alter table public.thrivefold_feature_unlocks enable row level security;
alter table public.thrivefold_reward_ledger enable row level security;
alter table public.thrivefold_feature_entitlements enable row level security;

revoke all on public.thrivefold_task_rewards, public.thrivefold_levels, public.thrivefold_feature_unlocks,
  public.thrivefold_reward_ledger, public.thrivefold_feature_entitlements from anon, authenticated;
grant select on public.thrivefold_task_rewards, public.thrivefold_levels, public.thrivefold_feature_unlocks to authenticated;
grant select on public.thrivefold_reward_ledger, public.thrivefold_feature_entitlements to authenticated;

create policy "catalog readable" on public.thrivefold_task_rewards for select to authenticated using (true);
create policy "levels readable" on public.thrivefold_levels for select to authenticated using (true);
create policy "unlocks readable" on public.thrivefold_feature_unlocks for select to authenticated using (true);
create policy "own ledger" on public.thrivefold_reward_ledger for select to authenticated using (user_id = (select auth.uid()));
create policy "own entitlements" on public.thrivefold_feature_entitlements for select to authenticated using (user_id = (select auth.uid()));

-- Level from XP: the highest catalog level reached, held at the first chapter checkpoint
-- (capstones are not available yet, so nobody advances past it).
create or replace function public.tf_level_for_xp(p_xp integer)
returns integer language sql stable set search_path = '' as $$
  select least(
    coalesce((select max(level) from public.thrivefold_levels where min_xp <= p_xp), 1),
    coalesce((select min(level) from public.thrivefold_levels where checkpoint_id is not null), 1000)
  )
$$;

create or replace function public.tf_level_clear_diamonds(p_level integer)
returns integer language sql stable set search_path = '' as $$
  select case
    when exists (select 1 from public.thrivefold_levels where level = p_level and checkpoint_id is not null) then ${lc.chapterCheckpointLevel}
    when p_level % 10 = 0 then ${lc.everyTenthLevel}
    else ${lc.default}
  end
$$;

-- Issues level-clear diamonds the ledger does not hold yet. Idempotent.
create or replace function public.tf_settle_levels(p_user uuid, p_date date)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_xp integer;
  v_level integer;
begin
  select coalesce(sum(xp), 0) into v_xp from public.thrivefold_reward_ledger where user_id = p_user;
  v_level := public.tf_level_for_xp(v_xp);
  insert into public.thrivefold_reward_ledger (user_id, key, kind, diamonds, game_date, source_id, policy_version)
  select p_user, 'level_clear:' || l.level, 'level_clear', public.tf_level_clear_diamonds(l.level), p_date,
         'level-' || l.level, ${lit(economy.version)}
  from public.thrivefold_levels l
  where l.level < v_level
  on conflict (user_id, key) do nothing;
end;
$$;

-- Records a verified quest. The reward is read from the catalog table; the client only names
-- the assignment and task. Same assignment key twice returns the original result.
create or replace function public.tf_claim_task_reward(p_assignment_key text, p_task_id text, p_game_date date)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_user uuid := auth.uid();
  v_reward public.thrivefold_task_rewards;
  v_key text := 'task:' || p_assignment_key;
  v_claims integer;
begin
  if v_user is null then raise exception 'not authenticated'; end if;
  if public.tf_is_restricted(v_user, null) then raise exception 'account restricted'; end if;
  if p_game_date < current_date - 1 or p_game_date > current_date + 1 then raise exception 'stale game date'; end if;
  select * into v_reward from public.thrivefold_task_rewards where task_id = p_task_id;
  if not found then raise exception 'unknown task'; end if;
  if exists (select 1 from public.thrivefold_reward_ledger where user_id = v_user and key = v_key) then
    return jsonb_build_object('status', 'duplicate');
  end if;
  select count(*) into v_claims from public.thrivefold_reward_ledger
    where user_id = v_user and kind = 'task_reward' and game_date = p_game_date;
  if v_claims >= 6 then raise exception 'daily quest limit reached'; end if;

  perform pg_advisory_xact_lock(hashtext(v_user::text));
  insert into public.thrivefold_reward_ledger (user_id, key, kind, xp, task_points, game_date, source_id, policy_version)
  values (v_user, v_key, 'task_reward', v_reward.xp,
          case when v_reward.daily_goal_eligible then v_reward.task_points else 0 end,
          p_game_date, p_task_id, ${lit(economy.version)})
  on conflict (user_id, key) do nothing;
  perform public.tf_settle_levels(v_user, p_game_date);
  return jsonb_build_object('status', 'recorded', 'xp', v_reward.xp, 'task_points', v_reward.task_points);
end;
$$;

-- Spends diamonds and grants the entitlement in one transaction, or does nothing.
create or replace function public.tf_unlock_feature(p_feature_id text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_user uuid := auth.uid();
  v_unlock public.thrivefold_feature_unlocks;
  v_xp integer;
  v_diamonds integer;
begin
  if v_user is null then raise exception 'not authenticated'; end if;
  if public.tf_is_restricted(v_user, null) then raise exception 'account restricted'; end if;
  perform pg_advisory_xact_lock(hashtext(v_user::text));
  select * into v_unlock from public.thrivefold_feature_unlocks where id = p_feature_id;
  if not found then return jsonb_build_object('ok', false, 'block', 'UNKNOWN_FEATURE'); end if;
  if exists (select 1 from public.thrivefold_feature_entitlements where user_id = v_user and feature_id = p_feature_id) then
    return jsonb_build_object('ok', false, 'block', 'OWNED');
  end if;
  select coalesce(sum(xp), 0), coalesce(sum(diamonds), 0) into v_xp, v_diamonds
    from public.thrivefold_reward_ledger where user_id = v_user;
  if public.tf_level_for_xp(v_xp) < v_unlock.min_level then
    return jsonb_build_object('ok', false, 'block', 'LEVEL_TOO_LOW');
  end if;
  if v_diamonds < v_unlock.cost then return jsonb_build_object('ok', false, 'block', 'INSUFFICIENT_DIAMONDS'); end if;
  insert into public.thrivefold_reward_ledger (user_id, key, kind, diamonds, game_date, source_id, policy_version)
  values (v_user, 'unlock:' || p_feature_id, 'unlock_spend', -v_unlock.cost, current_date, p_feature_id, ${lit(economy.version)});
  insert into public.thrivefold_feature_entitlements (user_id, feature_id) values (v_user, p_feature_id);
  return jsonb_build_object('ok', true, 'diamonds', v_diamonds - v_unlock.cost);
end;
$$;

-- Balance summary for the signed-in person.
create or replace function public.tf_my_progress()
returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'xp', coalesce(sum(xp), 0),
    'diamonds', coalesce(sum(diamonds), 0),
    'level', public.tf_level_for_xp(coalesce(sum(xp), 0)::integer)
  )
  from public.thrivefold_reward_ledger where user_id = auth.uid()
$$;

revoke all on function public.tf_settle_levels(uuid, date) from public, anon, authenticated;
revoke all on function public.tf_claim_task_reward(text, text, date) from public, anon;
revoke all on function public.tf_unlock_feature(text) from public, anon;
revoke all on function public.tf_my_progress() from public, anon;
grant execute on function public.tf_claim_task_reward(text, text, date) to authenticated;
grant execute on function public.tf_unlock_feature(text) to authenticated;
grant execute on function public.tf_my_progress() to authenticated;

insert into public.thrivefold_task_rewards (task_id, task_points, xp, daily_goal_eligible) values
  ${tasks}
on conflict (task_id) do update set task_points = excluded.task_points, xp = excluded.xp,
  daily_goal_eligible = excluded.daily_goal_eligible;

insert into public.thrivefold_levels (level, min_xp, checkpoint_id) values
  ${levels}
on conflict (level) do update set min_xp = excluded.min_xp, checkpoint_id = excluded.checkpoint_id;

insert into public.thrivefold_feature_unlocks (id, cost, min_level) values
  ${unlocks}
on conflict (id) do update set cost = excluded.cost, min_level = excluded.min_level;
`;

fs.writeFileSync('supabase/migrations/20261023000005_thrivefold_progression.sql', sql);
console.log('wrote supabase/migrations/20261023000005_thrivefold_progression.sql');
